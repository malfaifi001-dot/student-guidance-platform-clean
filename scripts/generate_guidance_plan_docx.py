def set_cell_shading(cell, fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn('w:shd'))
    if shd is None:
        shd = OxmlElement('w:shd')
        tc_pr.append(shd)
    shd.set(qn('w:fill'), fill)


def set_cell_margins(cell, top=80, start=90, bottom=80, end=90):
    tc = cell._tc
    tc_pr = tc.get_or_add_tcPr()
    tc_mar = tc_pr.first_child_found_in('w:tcMar')
    if tc_mar is None:
        tc_mar = OxmlElement('w:tcMar')
        tc_pr.append(tc_mar)
    for m, v in [('top', top), ('start', start), ('bottom', bottom), ('end', end)]:
        node = tc_mar.find(qn(f'w:{m}'))
        if node is None:
            node = OxmlElement(f'w:{m}')
            tc_mar.append(node)
        node.set(qn('w:w'), str(v))
        node.set(qn('w:type'), 'dxa')


def set_cell_border(cell, color='D5DEDB', size='6'):
    tc_pr = cell._tc.get_or_add_tcPr()
    borders = tc_pr.first_child_found_in('w:tcBorders')
    if borders is None:
        borders = OxmlElement('w:tcBorders')
        tc_pr.append(borders)
    for edge in ('top', 'left', 'bottom', 'right', 'insideH', 'insideV'):
        tag = borders.find(qn(f'w:{edge}'))
        if tag is None:
            tag = OxmlElement(f'w:{edge}')
            borders.append(tag)
        tag.set(qn('w:val'), 'single')
        tag.set(qn('w:sz'), size)
        tag.set(qn('w:space'), '0')
        tag.set(qn('w:color'), color)


def set_repeat_table_header(row):
    tr_pr = row._tr.get_or_add_trPr()
    tbl_header = OxmlElement('w:tblHeader')
    tbl_header.set(qn('w:val'), 'true')
    tr_pr.append(tbl_header)


def set_paragraph_rtl(paragraph, alignment=WD_ALIGN_PARAGRAPH.RIGHT):
    paragraph.alignment = alignment
    p_pr = paragraph._p.get_or_add_pPr()
    bidi = p_pr.find(qn('w:bidi'))
    if bidi is None:
        bidi = OxmlElement('w:bidi')
        p_pr.append(bidi)
    bidi.set(qn('w:val'), '1')
    paragraph.paragraph_format.space_after = Pt(0)
    paragraph.paragraph_format.space_before = Pt(0)


def style_run(run, size=10, bold=False, color=COLORS['black'], font='Arial'):
    run.font.name = font
    run.font.size = Pt(size)
    run.bold = bold
    run.font.color.rgb = RGBColor.from_string(color)
    r_pr = run._element.get_or_add_rPr()
    r_fonts = r_pr.rFonts
    if r_fonts is None:
        r_fonts = OxmlElement('w:rFonts')
        r_pr.insert(0, r_fonts)
    r_fonts.set(qn('w:ascii'), font)
    r_fonts.set(qn('w:hAnsi'), font)
    r_fonts.set(qn('w:cs'), font)


def set_cell_text(cell, text, size=9, bold=False, color=COLORS['black'], align=WD_ALIGN_PARAGRAPH.CENTER):
    cell.text = ''
    p = cell.paragraphs[0]
    set_paragraph_rtl(p, align)
    r = p.add_run(str(text))
    style_run(r, size=size, bold=bold, color=color)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    set_cell_margins(cell)
    set_cell_border(cell)


def set_table_widths(table, widths_cm):
    for row in table.rows:
        for idx, width in enumerate(widths_cm):
            if idx < len(row.cells):
                row.cells[idx].width = Cm(width)


def add_section_title(doc, title, subtitle=None, color=None):
    color = color or COLORS['green']
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True
    cell = table.cell(0, 0)
    set_cell_shading(cell, color)
    set_cell_border(cell, color=color, size='10')
    p = cell.paragraphs[0]
    set_paragraph_rtl(p, WD_ALIGN_PARAGRAPH.CENTER)
    r = p.add_run(title)
    style_run(r, size=16, bold=True, color=COLORS['white'])
    if subtitle:
        p2 = cell.add_paragraph()
        set_paragraph_rtl(p2, WD_ALIGN_PARAGRAPH.CENTER)
        r2 = p2.add_run(subtitle)
        style_run(r2, size=10, bold=False, color=COLORS['white'])
    doc.add_paragraph()


def add_text_block(doc, text, size=11, color=COLORS['black'], bold=False, center=False):
    p = doc.add_paragraph()
    set_paragraph_rtl(p, WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.RIGHT)
    p.paragraph_format.line_spacing = 1.25
    r = p.add_run(text)
    style_run(r, size=size, bold=bold, color=color)
    return p


def add_simple_table(doc, headers, rows, widths=None, header_color=None, font_size=9):
    header_color = header_color or COLORS['green']
    table = doc.add_table(rows=1, cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = 'Table Grid'
    hdr = table.rows[0]
    set_repeat_table_header(hdr)
    for i, h in enumerate(headers):
        set_cell_text(hdr.cells[i], h, size=9, bold=True, color=COLORS['white'])
        set_cell_shading(hdr.cells[i], header_color)
        set_cell_border(hdr.cells[i], color=header_color, size='8')
    for r_idx, row in enumerate(rows):
        cells = table.add_row().cells
        for c_idx, value in enumerate(row):
            align = WD_ALIGN_PARAGRAPH.RIGHT if c_idx not in (0, len(row)-1) else WD_ALIGN_PARAGRAPH.CENTER
            set_cell_text(cells[c_idx], value, size=font_size, align=align)
            set_cell_shading(cells[c_idx], COLORS['white'] if r_idx % 2 == 0 else COLORS['gray_light'])
    if widths:
        set_table_widths(table, widths)
    doc.add_paragraph()
    return table


def add_page_number(paragraph):
    set_paragraph_rtl(paragraph, WD_ALIGN_PARAGRAPH.CENTER)
    run = paragraph.add_run('صفحة ')
    style_run(run, size=8, color=COLORS['gray'])
    fld_char1 = OxmlElement('w:fldChar')
    fld_char1.set(qn('w:fldCharType'), 'begin')
    instr_text = OxmlElement('w:instrText')
    instr_text.set(qn('xml:space'), 'preserve')
    instr_text.text = 'PAGE'
    fld_char2 = OxmlElement('w:fldChar')
    fld_char2.set(qn('w:fldCharType'), 'end')
    run._r.append(fld_char1)
    run._r.append(instr_text)
    run._r.append(fld_char2)


def configure_section(section, landscape=False):
    section.page_width = Cm(29.7 if landscape else 21)
    section.page_height = Cm(21 if landscape else 29.7)
    section.orientation = WD_ORIENT.LANDSCAPE if landscape else WD_ORIENT.PORTRAIT
    section.top_margin = Cm(1.2)
    section.bottom_margin = Cm(1.2)
    section.right_margin = Cm(1.2)
    section.left_margin = Cm(1.2)
    section.header_distance = Cm(0.5)
    section.footer_distance = Cm(0.5)
    footer = section.footer.paragraphs[0]
    add_page_number(footer)


