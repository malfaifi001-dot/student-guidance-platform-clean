def add_week_page(doc, week):
    doc.add_page_break()
    add_section_title(doc, week['name'], week['period'], color=COLORS['green'])
    info = doc.add_table(rows=2, cols=4)
    info.alignment = WD_TABLE_ALIGNMENT.CENTER
    labels = [('محور الأسبوع', week['focus']), ('الهدف العام', week['goal'])]
    for row_i, (label, value) in enumerate(labels):
        set_cell_text(info.cell(row_i, 0), label, size=9, bold=True, color=COLORS['white'])
        set_cell_shading(info.cell(row_i, 0), COLORS['blue'])
        merged = info.cell(row_i, 1).merge(info.cell(row_i, 3))
        set_cell_text(merged, value, size=9.2, align=WD_ALIGN_PARAGRAPH.RIGHT)
        set_cell_shading(merged, COLORS['blue_light'])
    set_table_widths(info, [3.8, 7, 7, 7])
    doc.add_paragraph()

    headers = ['اليوم والتاريخ', 'المجال', 'البرنامج أو الخدمة', 'الإجراء المختصر', 'المشارك', 'الشاهد', 'الحالة']
    table = doc.add_table(rows=1, cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = 'Table Grid'
    set_repeat_table_header(table.rows[0])
    for i, h in enumerate(headers):
        set_cell_text(table.rows[0].cells[i], h, size=8.5, bold=True, color=COLORS['white'])
        set_cell_shading(table.rows[0].cells[i], COLORS['green'])
        set_cell_border(table.rows[0].cells[i], color=COLORS['green'], size='8')
    for day in week['days']:
        cells = table.add_row().cells
        values = [day[0], day[1], day[2], day[3], day[4], day[5], '☐ تم\n☐ لم يتم']
        fg, bg = CATEGORY_STYLE.get(day[1], (COLORS['gray'], COLORS['gray_light']))
        for i, val in enumerate(values):
            align = WD_ALIGN_PARAGRAPH.RIGHT if i in (2, 3, 4, 5) else WD_ALIGN_PARAGRAPH.CENTER
            set_cell_text(cells[i], val, size=7.7 if i == 3 else 8, align=align)
            set_cell_shading(cells[i], bg if i in (1, 2) else COLORS['white'])
        for run in cells[1].paragraphs[0].runs:
            run.font.color.rgb = RGBColor.from_string(fg)
            run.bold = True
    set_table_widths(table, [3.5, 2.2, 4.4, 8.3, 3.7, 3.7, 2.4])
    doc.add_paragraph()

    bottom = doc.add_table(rows=1, cols=2)
    bottom.alignment = WD_TABLE_ALIGNMENT.CENTER
    indicators_cell = bottom.cell(0, 0)
    fixed_cell = bottom.cell(0, 1)
    set_cell_border(indicators_cell, color=COLORS['gold'], size='8')
    set_cell_border(fixed_cell, color=COLORS['purple'], size='8')
    set_cell_shading(indicators_cell, COLORS['gold_light'])
    set_cell_shading(fixed_cell, COLORS['purple_light'])

    p = indicators_cell.paragraphs[0]
    set_paragraph_rtl(p, WD_ALIGN_PARAGRAPH.RIGHT)
    r = p.add_run('مؤشرات تحقق الأسبوع\n')
    style_run(r, size=9.5, bold=True, color=COLORS['yellow'])
    for item in week['indicators']:
        r = p.add_run('☐ ' + item + '\n')
        style_run(r, size=8.2, color=COLORS['black'])

    p2 = fixed_cell.paragraphs[0]
    set_paragraph_rtl(p2, WD_ALIGN_PARAGRAPH.RIGHT)
    r = p2.add_run('الأعمال الثابتة خلال الأسبوع\n')
    style_run(r, size=9.5, bold=True, color=COLORS['purple'])
    for item in ['استقبال الحالات والإحالات.', 'متابعة الغياب والتأخر.', 'التواصل مع الأسرة عند الحاجة.', 'توثيق الخدمات والشواهد.']:
        r = p2.add_run('☐ ' + item + '\n')
        style_run(r, size=8.2, color=COLORS['black'])
    set_table_widths(bottom, [13.7, 13.7])


